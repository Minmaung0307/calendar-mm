import assert from 'node:assert/strict';
import {buildCalendar,escapeText} from '../public/calendarExport.js';
const stamp=new Date('2026-10-17T18:00:00Z');
const all=buildCalendar({startYear:2026,stamp});
assert.equal(all.count,365);
const leap=buildCalendar({startYear:2028,stamp});assert.equal(leap.count,366);
assert.ok(leap.text.includes('DTSTART;VALUE=DATE:20280229\r\nDTEND;VALUE=DATE:20280301'));
assert.ok(all.text.includes('DTSTART;VALUE=DATE:20261231\r\nDTEND;VALUE=DATE:20270101'));
assert.ok(all.text.includes('DTSTAMP:20261017T180000Z'));
assert.equal(all.text.match(/BEGIN:VEVENT/g).length,365);
assert.equal(all.text.includes('BEGIN:VALARM'),false);
assert.equal(all.text.match(/TRANSP:TRANSPARENT/g).length,365);
assert.equal(all.text.replace(/\r\n/g,'').includes('\n'),false);
for(const line of all.text.split('\r\n'))assert.ok(Buffer.byteLength(line,'utf8')<=75);
const unfolded=all.text.replace(/\r\n /g,'');assert.ok(unfolded.includes('သီတင်းကျွတ်'));assert.ok(!unfolded.includes('\uFFFD'));
const special=buildCalendar({startYear:2026,mode:'special',stamp});assert.ok(special.count>40&&special.count<200);
const events=special.text.replace(/\r\n /g,'').split('BEGIN:VEVENT').slice(1);
assert.ok(events.some(e=>e.includes('DTSTART;VALUE=DATE:20261026')&&e.includes('သီတင်းကျွတ်')));
const ids=x=>[...x.matchAll(/UID:([^\r]+)/g)].map(m=>m[1]);assert.equal(new Set(ids(all.text)).size,365);assert.deepEqual(ids(all.text),ids(buildCalendar({startYear:2026,stamp}).text));
assert.equal(escapeText('a,b;c\\d\ne'),'a\\,b\\;c\\\\d\\ne');
assert.throws(()=>buildCalendar({startYear:1899}),RangeError);assert.throws(()=>buildCalendar({startYear:2099,endYear:2101}),RangeError);assert.throws(()=>buildCalendar({startYear:2026,mode:'bad'}),RangeError);
console.log('ICS checks passed: leap days, exclusive end dates, UTF-8 folding, escaping, stable UIDs, filters and bounds.');
